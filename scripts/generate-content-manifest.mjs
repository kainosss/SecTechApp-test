/**
 * Generates content/index.ts from the JSON files under /content so that
 * adding a device is just adding a file. Runs automatically before dev,
 * build and test (see package.json). Use --check to fail if it is stale.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..", "content");
const out = path.join(root, "index.ts");

/**
 * Each collection is a folder of JSON files; each file holds one record or
 * an array of records. Demonstration content lives under content/demo/ in the
 * same folder layout, so it is physically separate from real content.
 */
const COLLECTIONS = ["manufacturers", "sources", "devices", "wiring", "workflows"];
const ROOTS = ["", "demo"];

function filesIn(collection) {
  return ROOTS.flatMap((base) => {
    const dir = path.join(base, collection);
    const full = path.join(root, dir);
    if (!existsSync(full)) return [];
    return readdirSync(full)
      .filter((f) => f.endsWith(".json"))
      .sort()
      .map((f) => path.posix.join(...dir.split(path.sep), f));
  });
}

function identifier(collection, file, i) {
  return `${collection}_${i}_${file.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_")}`;
}

export function renderManifest() {
  const imports = [];
  const entries = [];
  for (const collection of COLLECTIONS) {
    const ids = filesIn(collection).map((file, i) => {
      const id = identifier(collection, file, i);
      imports.push(`import ${id} from "./${file}";`);
      return id;
    });
    entries.push(`  ${collection}: [${ids.map((id) => `${id}`).join(", ")}].flat() as unknown[],`);
  }
  return `// AUTO-GENERATED by scripts/generate-content-manifest.mjs. Do not edit by hand.
// Add content by creating JSON files under /content; this file is regenerated
// before dev, build and test.
${imports.join("\n")}

export const rawContent = {
${entries.join("\n")}
};
`;
}

const next = renderManifest();
const current = existsSync(out) ? readFileSync(out, "utf8") : "";

if (process.argv.includes("--check")) {
  if (current !== next) {
    console.error("content/index.ts is out of date. Run: npm run content:manifest");
    process.exit(1);
  }
} else if (current !== next) {
  writeFileSync(out, next);
  console.log("Updated content/index.ts");
}
