/**
 * HTTP security headers for every response (applied in next.config.ts). The
 * app is static, makes no third-party requests and loads fonts and scripts
 * from its own origin only. Next.js's inline bootstrap scripts need
 * 'unsafe-inline' unless nonces are used, and nonces would make every page
 * dynamic, so scripts are limited to this origin plus inline. The PDF preview
 * is a blob: iframe and downloads are blob: links.
 */
export function contentSecurityPolicy(dev = false): string {
  return [
    "default-src 'self'",
    `script-src 'self' 'unsafe-inline'${dev ? " 'unsafe-eval'" : ""}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self' data:",
    `connect-src 'self'${dev ? " ws: wss:" : ""}`,
    "frame-src 'self' blob:",
    "worker-src 'self' blob:",
    "manifest-src 'self'",
    "media-src 'none'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    ...(dev ? [] : ["upgrade-insecure-requests"]),
  ].join("; ");
}

export function securityHeaders(dev = false): { key: string; value: string }[] {
  return [
    { key: "Content-Security-Policy", value: contentSecurityPolicy(dev) },
    { key: "X-Content-Type-Options", value: "nosniff" },
    { key: "Referrer-Policy", value: "no-referrer" },
    { key: "X-Frame-Options", value: "DENY" },
    { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
    {
      key: "Permissions-Policy",
      value: "camera=(), microphone=(), geolocation=(), payment=(), usb=(), serial=(), bluetooth=(), hid=(), midi=(), interest-cohort=(), browsing-topics=()",
    },
    // HTTPS only once deployed (ignored by browsers over plain-HTTP localhost).
    ...(dev ? [] : [{ key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" }]),
    // Private pilot: not for search engines.
    { key: "X-Robots-Tag", value: "noindex, nofollow" },
  ];
}

export interface HeaderRule {
  /** Next.js path pattern (`/:path*`, `/icons/:file*`). */
  source: string;
  headers: { key: string; value: string }[];
}

/** Every response gets the security headers; the manifest and icons get cache rules (installed apps re-read them). */
export function headerRules(dev = false): HeaderRule[] {
  return [
    { source: "/:path*", headers: securityHeaders(dev) },
    { source: "/manifest.webmanifest", headers: [{ key: "Cache-Control", value: "public, max-age=0, must-revalidate" }] },
    { source: "/icons/:file*", headers: [{ key: "Cache-Control", value: "public, max-age=86400" }] },
  ];
}

/**
 * The same rules as a Cloudflare Pages `_headers` file (static hosting ignores
 * next.config headers). Matching rules combine, as with Next.js. Hashed build
 * assets are additionally marked immutable, as `next start` does.
 */
export function cloudflareHeadersFile(): string {
  const rules: HeaderRule[] = [
    ...headerRules(false),
    { source: "/_next/static/:file*", headers: [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }] },
  ];
  const lines = ["# Generated by scripts/build-static.mjs from src/lib/security-headers.ts — do not edit."];
  for (const rule of rules) {
    lines.push(rule.source.replace(/:[a-z]+\*$/i, "*"));
    for (const h of rule.headers) lines.push(`  ${h.key}: ${h.value}`);
  }
  return `${lines.join("\n")}\n`;
}
